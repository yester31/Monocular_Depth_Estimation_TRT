"""Load the multi-aspect-ratio evaluation manifest (data/eval/aspects.json).

This is the P2 counterpart to data/eval/diode_indoors.json: instead of ground
truth, it lists the 4:3 / 16:9 / portrait inputs used to check that
preprocessing and visualisation handle non-square images at all. The manifest
is generated by tools/prepare_eval_inputs.py -- this module only reads it.

A file that fails to load here does not get skipped and quietly dropped from
whatever consumes it (P7's demo among others): a missing manifest, a missing
image, a sha256 that no longer matches, or an entry missing one of the P7
contract keys all raise EvalInputError.
"""

import hashlib
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_MANIFEST = os.path.join(ROOT, "data", "eval", "aspects.json")

# The contract other readers (P7's demo among them) rely on -- see PLAN.md P2.
REQUIRED_KEYS = (
    "file", "aspect", "width", "height", "source", "license",
    "orig_file", "orig_width", "orig_height", "crop", "sha256",
)
VALID_ASPECTS = frozenset(("4:3", "16:9", "portrait"))


class EvalInputError(RuntimeError):
    """The manifest, or something it points at, is not what it claims to be."""


def _sha256(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(chunk), b""):
            h.update(block)
    return h.hexdigest()


def load_eval_inputs(manifest_path=DEFAULT_MANIFEST):
    """Return a list of (path, aspect, meta) for every manifest entry.

    `path` is an absolute path to the image file, `aspect` is one of
    "4:3" / "16:9" / "portrait", and `meta` is the full manifest entry dict.
    """
    if not os.path.isfile(manifest_path):
        raise EvalInputError(f"manifest not found: {manifest_path}")

    with open(manifest_path, "r", encoding="utf-8") as f:
        entries = json.load(f)
    if not isinstance(entries, list):
        raise EvalInputError(f"{manifest_path}: expected a JSON array of entries")

    base_dir = os.path.dirname(manifest_path)
    out = []
    for i, entry in enumerate(entries):
        missing = [k for k in REQUIRED_KEYS if k not in entry]
        if missing:
            raise EvalInputError(f"{manifest_path}[{i}]: missing keys {missing}")
        if entry["aspect"] not in VALID_ASPECTS:
            raise EvalInputError(
                f"{manifest_path}[{i}]: aspect {entry['aspect']!r} not in "
                f"{sorted(VALID_ASPECTS)}"
            )

        path = os.path.join(base_dir, entry["file"])
        if not os.path.isfile(path):
            raise EvalInputError(f"{manifest_path}[{i}]: image file not found: {path}")

        actual = _sha256(path)
        if actual != entry["sha256"]:
            raise EvalInputError(
                f"{manifest_path}[{i}]: sha256 mismatch for {entry['file']} "
                f"(manifest {entry['sha256']}, actual {actual})"
            )

        out.append((path, entry["aspect"], entry))
    return out
